import pandas as pd
import numpy as np
import logging
import os
import sys

# =====================================================
# LOGGING CONFIGURATION
# =====================================================

from utils.logger_config import setup_logging

logger = logging.getLogger(__name__)

# =====================================================
# LOAD CLEAN DATA
# =====================================================

def load_clean_data(filepath):
    """
    Load cleaned dataset generated by pipeline.py
    """

    try:
        df = pd.read_csv(filepath)

        logger.info(
            f"Clean dataset loaded successfully. "
            f"Rows={df.shape[0]}, Columns={df.shape[1]}"
        )

        return df

    except FileNotFoundError:
        logger.error(
            f"File not found: {filepath}",
            exc_info=True
        )
        sys.exit(1)

    except pd.errors.ParserError:
        logger.error(
            "CSV parsing error.",
            exc_info=True
        )
        sys.exit(1)

    except Exception:
        logger.error(
            "Unexpected error while loading dataset.",
            exc_info=True
        )
        sys.exit(1)


# =====================================================
# TIME FEATURES
# =====================================================

def create_time_features(df):

    logger.info("Creating time features.")

    df["date_time"] = pd.to_datetime(
        df["date_time"],
        errors="coerce"
    )

    # Hour of day
    df["hour"] = df["date_time"].dt.hour

    # Day of week
    df["day_of_week"] = (
        df["date_time"].dt.dayofweek
    )

    # Month
    df["month"] = (
        df["date_time"].dt.month
    )

    # Weekend indicator
    df["is_weekend"] = np.where(
        df["day_of_week"] >= 5,
        1,
        0
    )

    logger.info(
        "Created hour, day_of_week, month and is_weekend."
    )

    return df


# =====================================================
# CYCLICAL ENCODING
# =====================================================

def create_cyclical_features(df):

    logger.info(
        "Creating cyclical time features."
    )

    df["hour_sin"] = np.sin(
        2 * np.pi * df["hour"] / 24
    )

    df["hour_cos"] = np.cos(
        2 * np.pi * df["hour"] / 24
    )

    logger.info(
        "Created hour_sin and hour_cos."
    )

    return df


# =====================================================
# WEATHER FEATURES
# =====================================================

def create_weather_features(df):

    logger.info(
        "Creating weather features."
    )

    # Rain indicator
    df["is_raining"] = np.where(
        df["rain_1h"] > 0,
        1,
        0
    )

    # Snow indicator
    df["is_snowing"] = np.where(
        df["snow_1h"] > 0,
        1,
        0
    )

    # Poor weather indicator
    severe_weather = [
        "Rain",
        "Snow",
        "Thunderstorm",
        "Drizzle"
    ]

    df["bad_weather"] = np.where(
        df["weather_main"].isin(severe_weather),
        1,
        0
    )

    logger.info(
        "Created weather indicator variables."
    )

    return df


# =====================================================
# ENCODE CATEGORICAL WEATHER VARIABLES
# =====================================================

def encode_weather_categories(df):

    logger.info(
        "Encoding weather categories."
    )

    weather_encoded = pd.get_dummies(
        df["weather_main"],
        prefix="weather"
    )

    df = pd.concat(
        [df, weather_encoded],
        axis=1
    )

    logger.info(
        f"Created {weather_encoded.shape[1]} "
        f"encoded weather columns."
    )

    return df


# =====================================================
# SCALE NUMERICAL FEATURES
# =====================================================

def scale_features(df):

    logger.info(
        "Scaling numerical features."
    )

    # Temperature
    df["temp_scaled"] = (
        (df["temp"] - df["temp"].min())
        /
        (df["temp"].max() - df["temp"].min())
    )

    # Traffic volume
    df["traffic_volume_scaled"] = (
        (df["traffic_volume"] -
         df["traffic_volume"].min())
        /
        (df["traffic_volume"].max() -
         df["traffic_volume"].min())
    )

    logger.info(
        "Created temp_scaled and "
        "traffic_volume_scaled."
    )

    return df


# =====================================================
# CREATE CONGESTION TARGET
# =====================================================

def create_congestion_target(df):

    logger.info(
        "Creating congestion category."
    )

    q1 = df["traffic_volume"].quantile(0.25)
    q2 = df["traffic_volume"].quantile(0.50)
    q3 = df["traffic_volume"].quantile(0.75)

    logger.debug(
        f"Congestion thresholds: "
        f"Q1={q1:.2f}, "
        f"Q2={q2:.2f}, "
        f"Q3={q3:.2f}"
    )

    def classify_congestion(volume):

        if volume <= q1:
            return "Low"

        elif volume <= q2:
            return "Medium"

        elif volume <= q3:
            return "High"

        else:
            return "Very High"

    df["congestion_level"] = (
        df["traffic_volume"]
        .apply(classify_congestion)
    )

    logger.info(
        "Created congestion_level target."
    )

    return df


# =====================================================
# SAVE ML-READY DATASET
# =====================================================

def save_dataset(df, filepath):

    df.to_csv(
        filepath,
        index=False
    )

    logger.info(
        f"ML-ready dataset saved to {filepath}"
    )


# =====================================================
# FEATURE ENGINEERING PIPELINE
# =====================================================

def engineer_features(df):

    logger.info(
        f"Dataset BEFORE feature engineering: "
        f"{df.shape[0]} rows, "
        f"{df.shape[1]} columns"
    )

    df = create_time_features(df)

    df = create_cyclical_features(df)

    df = create_weather_features(df)

    df = encode_weather_categories(df)

    df = scale_features(df)

    df = create_congestion_target(df)

    logger.info(
        f"Dataset AFTER feature engineering: "
        f"{df.shape[0]} rows, "
        f"{df.shape[1]} columns"
    )

    return df


# =====================================================
# MAIN
# =====================================================

def main():

    setup_logging(
        "logs/feature_engineering.log",
        level=logging.INFO
    )

    try:

        logger.info(
            "Feature engineering pipeline started."
        )

        df = load_clean_data(
            "data/traffic_cleaned.csv"
        )

        df = engineer_features(df)

        save_dataset(
            df,
            "data/traffic_ml_ready.csv"
        )

        logger.info(
            "Feature engineering completed successfully."
        )

    except Exception:

        logger.error(
            "Feature engineering pipeline failed.",
            exc_info=True
        )

        sys.exit(1)


if __name__ == "__main__":
    main()